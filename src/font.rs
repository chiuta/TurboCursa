/// Folds an accented letter to its base letter; the bool tells the renderer to draw an accent pixel above it.
pub fn fold(c: char) -> (char, bool) {
    let u = c.to_uppercase().next().unwrap_or(c);
    let base = match u {
        'Ă' | 'Â' | 'Á' | 'À' | 'Ã' | 'Ä' => 'A',
        'É' | 'È' | 'Ê' | 'Ë' => 'E',
        'Î' | 'Í' | 'Ì' | 'Ï' => 'I',
        'Ó' | 'Ò' | 'Ô' | 'Õ' | 'Ö' | 'Ő' => 'O',
        'Ú' | 'Ù' | 'Û' | 'Ü' | 'Ű' => 'U',
        'Ș' | 'Ş' => 'S',
        'Ț' | 'Ţ' => 'T',
        'Ç' => 'C',
        'Ñ' => 'N',
        other => other,
    };
    (base, base != u)
}

pub fn glyph(c: char) -> Option<&'static str> {
    let c = fold(c).0.to_ascii_uppercase();
    GLYPHS.iter().find(|(g, _)| *g == c).map(|(_, s)| *s)
}

pub fn text_width(s: &str, scale: i32) -> i32 {
    s.chars().count() as i32 * 4 * scale - scale
}
