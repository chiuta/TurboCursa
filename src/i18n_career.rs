pub fn t(c: C) -> &'static str {
    T[c as usize][lang() as usize]
}

/// Template string with `{}` replaced by a number.
pub fn tn(c: C, n: usize) -> String {
    t(c).replace("{}", &n.to_string())
}

pub fn division(d: u8) -> &'static str {
    DIV[lang() as usize][(d as usize).min(4)]
}

pub fn continent(c: u8) -> &'static str {
    CONT[lang() as usize][(c as usize).min(5)]
}

/// All strings of every language (used by tests to check coverage of the pixel font).
pub fn all() -> impl Iterator<Item = &'static str> {
    T.iter()
        .flat_map(|r| r.iter().copied())
        .chain(DIV.iter().flat_map(|r| r.iter().copied()))
        .chain(CONT.iter().flat_map(|r| r.iter().copied()))
}
